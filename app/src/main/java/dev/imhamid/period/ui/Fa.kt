    /** Same text all day (so the Home card does not change on every redraw), a new one tomorrow. */
    private fun <T> pickDay(salt: Int, vararg v: T): T {
        val seed = LocalDate.now().toEpochDay() * 31 + salt
        return v[java.util.Random(seed).nextInt(v.size)]
    }

